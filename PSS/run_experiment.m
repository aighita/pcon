function h = run_experiment
% Porneste audiometrul furnizat si colecteaza metadatele experimentului.
root = fileparts(mfilename('fullpath'));
addpath(root,fullfile(root,'matlab'));
a = inputdlg({'Participant (nume sau initiale):','Casti/difuzoare si dispozitiv audio:',...
    'Conditiile incaperii / zgomot de fond:','Volumul sistemului si procesari audio (pastrate fixe):'},...
    'Experiment de egala tarie',[1 75],{'','','',''});
if isempty(a), h=[]; return; end
h = audiometru;
s = guidata(h);
assert(isempty(s.pss.masuratori),'Exista deja o sesiune activa. Inchideti audiometrul pentru una noua.');
s.pss.participant=a{1}; s.pss.echipament=a{2}; s.pss.mediu=a{3}; s.pss.volum=a{4};
guidata(h,s);
refs=get(s.phoniPop,'String'); k=find(str2double(refs)==30,1);
if ~isempty(k)
    set(s.phoniPop,'Value',k);
    audiometru('phoniPop_Callback',s.phoniPop,[],s);
end
uiwait(msgbox({'1. Eticheta foni din interfata este nominala: sistemul nu este calibrat SPL.',...
    '2. Alegeti referinta confortabila si un volum mic; apoi pastrati-le fixe.',...
    '3. Faceti cateva comparatii de acomodare fara Memorare.',...
    '4. Play test reda TEST 0.5 s + pauza 0.2 s + REFERINTA 0.5 s.',...
    '5. Modificati numai nivelul testului pana cand taria pare egala, apoi Memorare.',...
    '6. Repetati de minimum 3 ori la fiecare din cele 9 frecvente, inclusiv 1000 Hz.',...
    '7. Daca un ton nu poate fi comparat confortabil, sariti-l si explicati in observatii.',...
    '8. La sfarsit rulati finalizeaza_experiment in Command Window.'},...
    'Procedura experimentului','help','modal'));
end
