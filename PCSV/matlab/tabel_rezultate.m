function T = tabel_rezultate(d,nume)
s=d.selected;n=numel(s);
T=table(repmat({nume},n,1),{s.tip}',[s.m]',[s.m]'+1,[s.start]'+1,...
    [s.t_start]',[s.t_end]',repmat(d.N,n,1),repmat(d.fs,n,1),...
    [s.lag2]',[s.lag3]',[s.f02]',[s.f03]',[s.energy]',[s.coherence]',[s.agree]',...
    'VariableNames',{'fisier','tip','m_0','index_final_MATLAB','index_initial_MATLAB',...
    't_initial_s','t_final_s','N','Fs_Hz','lambda2','lambda3','F0_v2_Hz','F0_v3_Hz',...
    'energie','coerenta','acord_variante'});
end
